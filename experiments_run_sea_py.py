import numpy as np
from tqdm import tqdm
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import SGDClassifier
from sklearn.tree import DecisionTreeClassifier
from sadel.pipeline import SADEL
from sadel.metrics import acc_f1, ece
from data_prep.prepare_sea import load_sea

def main():
    np.random.seed(0)
    X, y = load_sea()
    scaler = StandardScaler()
    X = scaler.fit_transform(X)

    # two light tabular learners with partial_fit
    models = [
        ("sgd",  SGDClassifier(loss="log_loss", random_state=0)),
        ("tree", DecisionTreeClassifier(max_depth=6, random_state=0)) # no partial_fit
    ]

    warm = 2000
    models[0][1].fit(X[:warm], y[:warm])
    models[1][1].fit(X[:warm], y[:warm])

    costs = np.array([1.0, 1.0])
    s = SADEL(n_classes=2, n_models=2, model_costs=costs)

    acc_hist, f1_hist, ece_hist = [], [], []
    for i in tqdm(range(warm, len(X))):
        x1, y1 = X[i:i+1], y[i:i+1]
        p0 = models[0][1].predict_proba(x1)
        # DecisionTree has predict_proba; refit rarely to approximate incremental
        if i % 500 == 0:
            models[1][1].fit(X[:i], y[:i])
        p1 = models[1][1].predict_proba(x1)
        probs_k = np.stack([p0, p1], axis=0)  # (K,1,2)

        active_idx, _ = s.select_models(per_model_competence=probs_k.mean(axis=2), budget=1.2)
        fused = s.fuse(probs_k, active_idx)

        acc, f1 = acc_f1(fused, y1)
        cal = ece(fused, y1)
        acc_hist.append(acc); f1_hist.append(f1); ece_hist.append(cal)

        # online update
        models[0][1].partial_fit(x1, y1, classes=[0,1])

    print(f"[SEA] ACC={np.mean(acc_hist):.4f} F1={np.mean(f1_hist):.4f} ECE={np.mean(ece_hist):.4f}")

if __name__ == "__main__":
    main()