import numpy as np
from tqdm import tqdm
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import SGDClassifier
from sklearn.naive_bayes import GaussianNB
from sadel.pipeline import SADEL
from sadel.metrics import acc_f1, ece
from data_prep.prepare_electricity import load_electricity

def proba(clf, x):
    if hasattr(clf, "predict_proba"):
        return clf.predict_proba(x)
    s = clf.decision_function(x).reshape(-1,1)
    p1 = 1/(1+np.exp(-s))
    return np.hstack([1-p1, p1])

def main():
    np.random.seed(0)
    X, y = load_electricity(limit=45000)
    scaler = StandardScaler()
    X = scaler.fit_transform(X)

    models = [
        ("sgd", SGDClassifier(loss="log_loss", random_state=0)),
        ("gnb", GaussianNB()),
    ]
    warm = 2000
    for _, m in models:
        m.fit(X[:warm], y[:warm])

    costs = np.array([1.0, 1.0])
    s = SADEL(n_classes=2, n_models=2, model_costs=costs)

    acc_hist, f1_hist, ece_hist = [], [], []
    for i in tqdm(range(warm, len(X))):
        x1, y1 = X[i:i+1], y[i:i+1]
        p0 = proba(models[0][1], x1)
        p1 = proba(models[1][1], x1)
        probs_k = np.stack([p0, p1], axis=0)

        active_idx, _ = s.select_models(per_model_competence=probs_k.mean(axis=2), budget=1.2)
        fused = s.fuse(probs_k, active_idx)

        acc, f1 = acc_f1(fused, y1)
        cal = ece(fused, y1)
        acc_hist.append(acc); f1_hist.append(f1); ece_hist.append(cal)

        # online updates
        models[0][1].partial_fit(x1, y1, classes=[0,1])
        models[1][1].partial_fit(x1, y1)

    print(f"[Electricity] ACC={np.mean(acc_hist):.4f} F1={np.mean(f1_hist):.4f} ECE={np.mean(ece_hist):.4f}")

if __name__ == "__main__":
    main()