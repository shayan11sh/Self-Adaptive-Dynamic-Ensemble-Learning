import numpy as np, torch
from tqdm import tqdm
from sadel.model_zoo import SmallCNN, torch_predict_proba
from sadel.pipeline import SADEL
from sadel.metrics import acc_f1, ece
from sadel.utils import train_step, RollingStat
from data_prep.prepare_cifar10_drift import get_warmup_loader, stream

DEVICE = 'cuda' if torch.cuda.is_available() else 'cpu'
N_CLASSES = 10

def warmup(models, steps=300, lr=1e-3):
    optims = [torch.optim.Adam(m.parameters(), lr=lr) for m in models]
    loader = get_warmup_loader()
    it = 0
    for xb, yb in loader:
        for m, opt in zip(models, optims):
            train_step(m, xb.to(DEVICE), yb.to(DEVICE), opt, DEVICE)
        it += 1
        if it >= steps: break

def main():
    torch.manual_seed(0); np.random.seed(0)

    models = [SmallCNN(in_ch=3, n_classes=N_CLASSES).to(DEVICE) for _ in range(3)]
    warmup(models, steps=300, lr=1e-3)

    costs = np.array([1.0, 1.2, 1.5])
    s = SADEL(n_classes=N_CLASSES, n_models=len(models), model_costs=costs)

    acc_roll = RollingStat(500)
    acc_hist, f1_hist, ece_hist = [], [], []

    for xb, yb in tqdm(stream(device=DEVICE), desc="CIFAR10-Drift"):
        probs_k = np.stack([torch_predict_proba(m, xb, DEVICE) for m in models], axis=0)  # (K,B,C)
        competence = probs_k.max(axis=2)

        active_idx, _ = s.select_models(per_model_competence=competence, budget=1.6)
        fused = s.fuse(probs_k, active_idx)

        acc, f1 = acc_f1(fused, yb.cpu().numpy())
        cal = ece(fused, yb.cpu().numpy())
        acc_hist.append(acc); f1_hist.append(f1); ece_hist.append(cal)
        acc_roll.add(acc)

    print(f"[CIFAR10-Drift] ACC={np.mean(acc_hist):.4f} F1={np.mean(f1_hist):.4f} ECE={np.mean(ece_hist):.4f}")

if __name__ == "__main__":
    main()